"""Data-quality tables and the markdown report. Every number here is computed from the data."""

import pandas as pd

from queueiq.cleaning.flags import FLAGS

# Required fields and which rows each one is required for. Event dates only matter for
# rows with that status (an active project is *supposed* to have no withdrawal date).
REQUIRED_FIELDS: dict[str, tuple[str, str | None]] = {
    "queue_date": ("queue_date", None),
    "status": ("status", None),
    "withdrawal_date (withdrawn rows)": ("withdrawal_date", "withdrawn"),
    "operation_date (operational rows)": ("operation_date", "operational"),
    "county": ("county", None),
    "state": ("state", None),
    "iso": ("iso", None),
    "capacity_mw": ("capacity_mw", None),
    "fuel_type": ("fuel_type", None),
}

EXAMPLE_COLUMNS = [
    "project_id",
    "iso",
    "status",
    "queue_date",
    "operation_date",
    "withdrawal_date",
    "capacity_mw",
    "fuel_type_detail",
]


def missingness_table(df: pd.DataFrame, by: str) -> pd.DataFrame:
    """Percent missing for each required field within each group of `by` (plus 'All')."""
    groups = df[by].astype("string").fillna("(missing)")
    rows = {}
    for label, frame in [*df.groupby(groups, sort=True), ("All", df)]:
        row = {"rows": len(frame)}
        for field, (col, status) in REQUIRED_FIELDS.items():
            subset = frame if status is None else frame[frame["status"] == status]
            row[field] = round(100 * subset[col].isna().mean(), 1) if len(subset) else None
        rows[label] = row
    table = pd.DataFrame.from_dict(rows, orient="index")
    table.index.name = f"group ({by})"  # distinct from the 'iso' field column
    return table


def flag_summary(df: pd.DataFrame, scope_isos: tuple[str, ...]) -> pd.DataFrame:
    in_isos = df["iso"].isin(scope_isos)
    return pd.DataFrame(
        [
            {
                "flag": name,
                "meaning": meaning,
                "rows_all": int(df[f"flag_{name}"].sum()),
                "rows_in_model_isos": int(df.loc[in_isos, f"flag_{name}"].sum()),
            }
            for name, meaning in FLAGS.items()
        ]
    )


def flag_examples(df: pd.DataFrame, name: str, n: int = 5) -> pd.DataFrame:
    """First n flagged rows; for capacity flags, the most extreme ones."""
    hit = df[df[f"flag_{name}"]]
    if name == "huge_capacity":
        hit = hit.sort_values("capacity_mw", ascending=False)
    elif name == "nonpositive_capacity":
        hit = hit.sort_values("capacity_mw")
    elif name == "duplicate_queue_id":  # show each pair together
        hit = hit.assign(_base=hit["project_id"].str.replace(r"#\d+$", "", regex=True))
        hit = hit.sort_values(["_base", "project_id"])
    return hit[EXAMPLE_COLUMNS].head(n)


def to_markdown(df: pd.DataFrame, index: bool = False) -> str:
    """Small markdown table writer (avoids an extra dependency)."""
    if index:
        df = df.reset_index()

    def fmt(v) -> str:
        if pd.isna(v):
            return ""
        text = v.date().isoformat() if isinstance(v, pd.Timestamp) else str(v)
        return text.replace("|", "\\|")  # a raw pipe would split the cell

    header = "| " + " | ".join(map(str, df.columns)) + " |"
    sep = "|" + "|".join("---" for _ in df.columns) + "|"
    body = ["| " + " | ".join(fmt(v) for v in row) + " |" for row in df.itertuples(index=False)]
    return "\n".join([header, sep, *body])


def build_report(df: pd.DataFrame, waterfall: pd.DataFrame, meta: dict, scope_isos) -> str:
    scoped = df[df["in_model_scope"]]
    status_counts = df["status"].value_counts(dropna=False).rename_axis("status").reset_index()
    iso_counts = df["iso"].value_counts(dropna=False).rename_axis("iso").reset_index()
    scope_outcomes = pd.crosstab(scoped["iso"], scoped["outcome"], margins=True, margins_name="All")
    dates = pd.DataFrame(
        [
            {
                "column": c,
                "min": df[c].min(),
                "max": df[c].max(),
                "non_missing": int(df[c].notna().sum()),
            }
            for c in ["queue_date", "operation_date", "withdrawal_date"]
        ]
    )

    parts = [
        "# Data-quality report (generated by `make data`, do not edit by hand)",
        "",
        f"- Source file: `{meta['file']}`",
        f"- SHA-256: `{meta['sha256']}`",
        f"- Sheet: `{meta['sheet']}`",
        f"- Data cutoff (censoring date): {meta['cutoff']}",
        f"- Rows read: {len(df)}; rows in model scope: {len(scoped)}",
        "",
        "## Rows by status (all rows)",
        to_markdown(status_counts),
        "",
        "## Rows by region (all rows)",
        to_markdown(iso_counts),
        "",
        "## Date ranges (all rows)",
        to_markdown(dates),
        "",
        "## Cleaning waterfall (model scope)",
        "Rules are applied in order; each excluded row is counted at the first rule it fails. "
        "No row is deleted from `queue_entries.parquet`: excluded rows keep "
        "`in_model_scope = False` and their `scope_exclusion_reason`.",
        "",
        to_markdown(waterfall),
        "",
        "## Outcomes in model scope",
        to_markdown(scope_outcomes, index=True),
        "",
        "## Missingness of required fields by region (% missing)",
        "Event dates are measured only on rows with that status.",
        "",
        to_markdown(missingness_table(df, "iso"), index=True),
        "",
        "## Missingness of required fields by entry year (% missing)",
        to_markdown(missingness_table(df, "queue_year"), index=True),
        "",
        f"## Missingness by entry year, model regions only ({', '.join(scope_isos)}; % missing)",
        "Rows in these regions before any other scope rule is applied.",
        "",
        to_markdown(missingness_table(df[df["iso"].isin(scope_isos)], "queue_year"), index=True),
        "",
        "## Suspicious cases (flags)",
        f"`rows_in_model_isos` counts rows in {', '.join(scope_isos)} before any scope rule.",
        "",
        to_markdown(flag_summary(df, scope_isos)),
        "",
    ]
    for name in FLAGS:
        if df[f"flag_{name}"].any():
            parts += [f"### Examples: {name}", to_markdown(flag_examples(df, name)), ""]
    return "\n".join(parts)
