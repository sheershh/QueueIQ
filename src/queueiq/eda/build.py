"""`make eda`: reports/eda.md and reports/figures/*.png from the processed dataset.

Every number in the report is computed here at build time. The few sentences of
interpretation are written around those computed values.
"""

import matplotlib.pyplot as plt
import pandas as pd

from queueiq import config
from queueiq.cleaning.report import to_markdown
from queueiq.cleaning.scope import MIN_ENTRY_YEAR, MODEL_ISOS
from queueiq.eda import figures as F
from queueiq.eda import tables as T

PROCESSED_FILE = config.PROCESSED_DIR / "queue_entries.parquet"
INTERIM_FILE = config.INTERIM_DIR / "lbnl_queue_sheet.parquet"
REPORT_FILE = config.REPORTS_DIR / "eda.md"
FUEL_ORDER = ["solar", "wind", "battery", "gas", "other"]


def save(fig: plt.Figure, name: str) -> str:
    path = config.FIGURES_DIR / name
    fig.savefig(path, bbox_inches="tight")
    plt.close(fig)
    return f"figures/{name}"


def pct(x: float) -> str:
    return f"{x:.1f}%"


def main() -> None:
    config.ensure_dirs()
    df = pd.read_parquet(PROCESSED_FILE)
    raw = pd.read_parquet(INTERIM_FILE)
    cutoff = pd.Timestamp(config.DATA_CUTOFF)
    s = T.add_groups(T.in_scope(df))

    cohorts = T.cohort_table(s, cutoff)
    overall = T.cif_summary(s, None, cutoff)
    by_iso = T.cif_summary(s, "iso", cutoff)
    by_era = T.cif_summary(s, "era", cutoff)
    by_fuel = T.cif_summary(s, "fuel_group", cutoff).reindex(FUEL_ORDER)
    by_year = T.cif_summary(s, "queue_year", cutoff)
    by_year.index.name = "entry_year"
    years_5y = by_year[by_year["operational_by_5y_%"].notna()].index
    if len(years_5y) == 0:
        raise ValueError(f"No entry year has {T.MIN_AT_RISK}+ requests with 5 years of follow-up")
    last_5y = years_5y.max()
    durations_iso = T.observed_durations(s, "iso")
    durations_era = T.observed_durations(s, "era")
    capacity = T.capacity_by_fuel(s).reindex(FUEL_ORDER)
    shares_all = T.outcome_shares(df, "iso")
    check = T.lbnl_crosscheck(df, raw)

    curves_fuel = T.curves_by(s, "fuel_group")
    figs = {
        "requests": save(
            F.requests_per_year(s.groupby("queue_year").size(), "Requests per entry year"),
            "fig01_requests_per_year.png",
        ),
        "cohorts": save(
            F.cohort_outcomes(cohorts, "Status at the end of 2025, by entry year (raw shares)"),
            "fig02_status_by_entry_year.png",
        ),
        "overall": save(
            F.cif_overall(
                T.curves_by(s, None)["All"],
                "Cumulative share of requests reaching each outcome",
            ),
            "fig03_cif_overall.png",
        ),
        "iso": save(
            F.cif_small_multiples(T.curves_by(s, "iso"), "By region", ncols=2),
            "fig04_cif_by_region.png",
        ),
        "era": save(
            F.cif_small_multiples(T.curves_by(s, "era"), "By entry era", ncols=3),
            "fig05_cif_by_era.png",
        ),
        "fuel": save(
            F.cif_small_multiples(
                {k.capitalize(): curves_fuel[k] for k in FUEL_ORDER}, "By primary fuel", ncols=3
            ),
            "fig06_cif_by_fuel.png",
        ),
    }

    o = overall.loc["All"]
    n_events = s["outcome"].value_counts()
    censored_recent = cohorts.loc[cohorts.index >= 2022, "in_queue"]
    e_old = by_era.loc["2010-2014"]
    op5 = by_fuel["operational_by_5y_%"]
    xcheck_rows = "\n".join(
        [
            "| Capacity requesting interconnection 2000–2020: % operational by end of 2025 "
            f"| 13% | {check['mw_share_operational_%']}% |",
            f"| ... % withdrawn | 75% | {check['mw_share_withdrawn_%']}% |",
            f"| ... % still active | 10% | {check['mw_share_active_%']}% |",
            "| Median years from request to operation, projects online in 2025 | over 5 years "
            f"| {check['online_2025_median_years']} (n={check['online_2025_n']}) |",
        ]
    )
    recent_share = s.assign(recent=s["queue_year"] >= 2020).groupby("fuel_group")["recent"].mean()
    recent_share = recent_share.mul(100).round(1)
    y_last = by_year.loc[last_5y]
    recent_ops = int(((s["era"] == "2020-2025") & (s["outcome"] == "operational")).sum())

    md = f"""# Exploratory analysis (generated by `make eda`, do not edit by hand)

Data: LBNL Queued Up 2026 edition, cutoff {config.DATA_CUTOFF}. Unless a section says
otherwise, the numbers cover the **model scope**: {len(s):,} new-generation requests in
{", ".join(MODEL_ISOS)} that entered in {MIN_ENTRY_YEAR}–{int(s["queue_year"].max())}
(see `reports/data_quality.md` for how that scope was chosen).

Outcomes in scope: {n_events.get("withdrawn", 0):,} withdrawn,
{n_events.get("operational", 0):,} reached operation,
{n_events.get("censored", 0):,} still in the queue
(censored).

## Key findings

1. **Reaching operation is rare and slow.** Among requests with at least 3 years of follow-up,
   {pct(o["operational_by_3y_%"])} reached operation within 3 years. Among those with at least
   5 years ({int(o["full_5y_followup"]):,} requests, entered {years_5y.min()}–{last_5y}),
   {pct(o["operational_by_5y_%"])} reached operation within 5 years and
   {pct(o["withdrawn_by_5y_%"])} withdrew.
2. **Recent cohorts are mostly unresolved.** From 2022 on, between {pct(censored_recent.min())} and
   {pct(censored_recent.max())} of each year's requests are still in the queue. Their outcomes are
   mostly unknown, so raw "% operational" for recent years means little. This is why the models
   must handle censoring.
3. **Outcomes have shifted over time.** Within 5 years, {pct(e_old["operational_by_5y_%"])} of
   2010–2014 entrants reached operation, against {pct(y_last["operational_by_5y_%"])} of {last_5y}
   entrants. {last_5y} is the latest entry year with 5 full years of follow-up, so it is the only
   year from 2020 on that can be compared at 5 years ({int(y_last["full_5y_followup"]):,} requests).
   Withdrawal within 5 years: {pct(e_old["withdrawn_by_5y_%"])} against
   {pct(y_last["withdrawn_by_5y_%"])}. Only {recent_ops} requests from 2020–2025 have reached
   operation so far. Per-year values are in the table "Outcomes within 3 and 5 years by entry year".
4. **Fuel type matters a lot.** Share reaching operation within 5 years: gas {pct(op5["gas"])},
   wind {pct(op5["wind"])}, solar {pct(op5["solar"])}, battery {pct(op5["battery"])}. These are
   raw group comparisons, not effects: the fuel mix also changes across eras and regions (for
   example, {pct(recent_share["battery"])} of battery requests entered in 2020 or later, against
   {pct(recent_share["gas"])} of gas). Phase 4 models estimate these factors jointly.
5. **Our reading of the file matches LBNL's published figures** (see the cross-check below).

### What this means for modelling (Phases 3–5)
- Operation is the rare event. Test sets drawn from recent cohorts will contain very few
  operational events, so metrics for that event will be noisy. Report confidence intervals and
  per-cohort numbers.
- The change over time means a model trained on older cohorts may not transfer to newer ones.
  The rolling-origin backtest (train on the past, test on the next year) measures exactly that.
- Entry year (or era) and fuel type are strong candidate features.

## Requests per entry year
![Requests per entry year]({figs["requests"]})

## Status by entry year (raw, not censoring-aware)
Shares of each entry year's requests by status at the end of 2025. Recent years look as if
"nobody gets built", mostly because they haven't had time yet. `min/max_followup_years` is the
range of time each cohort has been observed.

![Status by entry year]({figs["cohorts"]})

{to_markdown(cohorts, index=True)}

## Censoring-aware outcome curves (Aalen-Johansen)
The curves estimate the cumulative share of requests reaching operation or withdrawing within
*t* years, using each project only for as long as it was observed. Curves stop once fewer than
{T.MIN_AT_RISK} projects are still observed.

**Read the curves with care.** Each curve pools entry years with different follow-up. Its early
part reflects all cohorts, and its tail reflects only the oldest. Because outcomes changed over
time, the tail is not "what happens to a typical project later on".

The **tables** avoid this. The 3- and 5-year figures use only requests that entered at least 3
(or 5) years before the cutoff, so every one was observed for the full horizon. `full_3y_followup`
and `full_5y_followup` count those requests. Cells are blank when fewer than {T.MIN_AT_RISK}
qualify.

![Overall curves]({figs["overall"]})

{to_markdown(overall, index=True)}

### Outcomes within 3 and 5 years by entry year
{to_markdown(by_year, index=True)}

### By region
![By region]({figs["iso"]})

{to_markdown(by_iso, index=True)}

### By entry era
![By era]({figs["era"]})

{to_markdown(by_era, index=True)}

### By primary fuel
![By fuel]({figs["fuel"]})

{to_markdown(by_fuel, index=True)}

## Time to outcome among projects that reached it
Median months from entry to the event, **counting only projects that had that event**. These
medians are biased short: slow projects that are still waiting are not counted. They describe
finished projects only, and are not estimates of waiting time for a new project.

{to_markdown(durations_iso, index=True)}

{to_markdown(durations_era, index=True)}

## Capacity by primary fuel
{to_markdown(capacity, index=True)}

## All regions (descriptive only, raw shares)
Raw status shares for every region, including those outside the model scope. Not
censoring-aware.

{to_markdown(shares_all, index=True)}

## Cross-check against LBNL's published figures
Computed on **all regions** with LBNL's definitions, to check that we read the file correctly.

| Figure | LBNL (emp.lbl.gov/queues) | This dataset |
|---|---|---|
{xcheck_rows}

Capacity here is the sum of `mw_1..mw_3`. LBNL's full report also adds imputed storage capacity
that is not in the data file, so small differences are expected.
"""
    REPORT_FILE.write_text(md)
    print(f"Wrote {REPORT_FILE.relative_to(config.PROJECT_ROOT)} and {len(figs)} figures")


if __name__ == "__main__":
    main()
